create table accounts (
 id uuid primary key, email varchar(254) not null unique,
 password_hash text, role varchar(20) not null check (role in ('CUSTOMER','ADMIN')),
 google_subject text unique
);
create table venues (
 id bigint generated by default as identity primary key,
 name varchar(120) not null, city varchar(120) not null,
 rows_count integer not null check (rows_count between 1 and 26),
 seats_per_row integer not null check (seats_per_row between 1 and 30)
);
create table events (
 id bigint generated by default as identity primary key,
 venue_id bigint not null references venues(id),
 title varchar(120) not null, category varchar(30) not null, starts_at timestamptz not null,
 price_cents integer not null check (price_cents between 100 and 10000000),
 version bigint not null default 0
);
create index events_starts_idx on events(starts_at,id);
create index events_category_idx on events(category,starts_at,id);
create table reservations (
 id uuid primary key, account_id uuid not null references accounts(id),
 event_id bigint not null references events(id),
 status varchar(24) not null check (status in ('HELD','CONFIRMED','PAYMENT_FAILED','CANCELLED')),
 expires_at timestamptz not null, created_at timestamptz not null default now(),
 total_cents integer not null check(total_cents > 0)
);
create index reservation_history_idx on reservations(account_id,created_at desc,id);
create table event_seats (
 event_id bigint not null references events(id),
 row_number integer not null, seat_number integer not null,
 reservation_id uuid references reservations(id), held_until timestamptz,
 primary key(event_id,row_number,seat_number)
);
create index event_seats_reservation_idx on event_seats(reservation_id) where reservation_id is not null;
create table reservation_items (
 reservation_id uuid not null references reservations(id),
 row_number integer not null, seat_number integer not null,
 unit_cents integer not null, primary key(reservation_id,row_number,seat_number)
);
create table payments (
 reservation_id uuid primary key references reservations(id),
 status varchar(20) not null check (status in ('PAID','DECLINED','REFUNDED')),
 amount_cents integer not null, updated_at timestamptz not null default now()
);
create table audit_log (
 id bigint generated always as identity primary key, actor uuid references accounts(id),
 action text not null, entity text not null, created_at timestamptz not null default now()
);
create table outbox (
 id uuid primary key, recipient varchar(254) not null, subject text not null, body text not null,
 attempts integer not null default 0, next_attempt timestamptz not null default now(),
 sent_at timestamptz, dead_at timestamptz
);
create index outbox_pending_idx on outbox(next_attempt,id) where sent_at is null and dead_at is null;
create table notification_deliveries (
 id uuid primary key, recipient varchar(254) not null, subject text not null, body text not null,
 delivery_mode varchar(16) not null, delivered_at timestamptz not null default now()
);
