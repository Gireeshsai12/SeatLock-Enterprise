import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';

test('customer registers, buys a seat, and receives a simulated refund',async ({page})=>{
  await page.goto('/');
  await expect(page.getByText('LOCAL DEMO')).toBeVisible();
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('button',{name:'Create an account'}).click();
  await page.getByLabel('Email').fill(`browser-${randomUUID()}@example.test`);
  await page.getByLabel('Password').fill(randomUUID());
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByRole('button',{name:'Sign out'})).toBeVisible();
  await page.getByLabel('Search events').fill('Midnight');
  await page.getByRole('article').filter({hasText:'Midnight Jazz Sessions'}).getByRole('button',{name:'Choose seats'}).click();
  await page.getByRole('button',{name:'Seat A1, available',exact:true}).click();
  await page.getByRole('button',{name:'Hold selected seats'}).click();
  await page.getByRole('button',{name:'Confirm demo payment'}).click();
  await expect(page.getByText('Reservation confirmed.',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'My reservations'}).click();
  await expect(page.getByRole('cell',{name:'PAID',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Cancel and simulate refund'}).click();
  await expect(page.getByRole('cell',{name:'REFUNDED',exact:true})).toBeVisible();
});

test('public catalog filters by event category on a narrow viewport',async ({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.getByLabel('Category').selectOption('SPORTS');
  await expect(page.getByRole('heading',{name:'Lowell City Finals'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Midnight Jazz Sessions'})).toHaveCount(0);
  await page.getByRole('button',{name:'Choose seats'}).click();
  await expect(page.getByRole('button',{name:'Seat A1, available',exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Your cart'})).toBeVisible();
});

test('administrator sees operations and runs reconciliation',async ({page})=>{
  const password=process.env.ADMIN_PASSWORD;
  test.skip(!password,'Set ADMIN_PASSWORD from the environment generated by startup.');
  await page.goto('/');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByLabel('Email').fill('admin@seatlock.local');
  await page.getByLabel('Password').fill(password!);
  await page.locator('form').getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('button',{name:'Operations'}).click();
  await expect(page.getByRole('heading',{name:'Recent audit log'})).toBeVisible();
  await page.getByRole('button',{name:'Reconcile inventory'}).click();
  await expect(page.getByText(/Released \d+ expired seat assignments/)).toBeVisible();
});
